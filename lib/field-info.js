/* The explanation for one field, or ''. */
export function fieldInfo(f, scope) {
  if (!f?.name) return '';
  if (f.info) return f.info;
  const leaf = f.name.split('.').pop();
  return FIELD_INFO[`${scope}:${f.name}`] || FIELD_INFO[f.name] || FIELD_INFO[wild(f.name)] || FIELD_INFO[`${scope}:${leaf}`] || FIELD_INFO[leaf] || f.hint || '';
}

